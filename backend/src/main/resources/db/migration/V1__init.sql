CREATE TABLE users
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               TEXT      NOT NULL,
    password_hash       TEXT        NOT NULL,
    first_name          TEXT        NOT NULL,
    last_name           TEXT NOT NULL ,
    room_number         TEXT         NOT NULL,
    floor_number        INT                 NOT NULL,
    role                TEXT         NOT NULL DEFAULT 'RESIDENT' CHECK (role IN ('RESIDENT', 'ADMIN', 'COUNCIL', 'STAFF')),
    status              TEXT         NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'PENDING_VERIFICATION', 'SUSPENDED')),
    created_at          TIMESTAMPTZ         NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_users_email ON users (email);

CREATE TABLE announcements
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id         BIGINT              NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title             TEXT        NOT NULL,
    content           TEXT                NOT NULL,
    category          TEXT        NOT NULL CHECK (category IN ('OFFICIAL', 'COUNCIL', 'SPONTANEOUS', 'GENERAL')),
    priority          TEXT        NOT NULL DEFAULT 'NORMAL' CHECK (priority IN ('NORMAL', 'IMPORTANT', 'URGENT')),
    is_pinned         BOOLEAN             NOT NULL DEFAULT FALSE,
    pinned_until      TIMESTAMPTZ,
    target_floor      INT,
    expires_at        TIMESTAMPTZ,
    status            TEXT        NOT NULL DEFAULT 'ACTIVE'  CHECK (status IN ('ACTIVE', 'CLOSED', 'ARCHIVED')),
    image_url         TEXT,
    created_at        TIMESTAMPTZ         NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ         NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_announcements_expires_at ON announcements (expires_at) WHERE expires_at IS NOT NULL;

CREATE TABLE announcement_comments
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id BIGINT              NOT NULL REFERENCES announcements (id) ON DELETE CASCADE,
    author_id       BIGINT              NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    content         TEXT                NOT NULL,
    created_at      TIMESTAMPTZ         NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ         NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_comments_announcement_id ON announcement_comments (announcement_id, created_at ASC);

CREATE TABLE announcement_reactions
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id BIGINT              NOT NULL REFERENCES announcements (id) ON DELETE CASCADE,
    user_id         BIGINT              NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    reaction_type   TEXT         NOT NULL DEFAULT 'LIKE' CHECK (reaction_type IN ('LIKE', 'JOIN', 'HELPFUL')),
    created_at      TIMESTAMPTZ         NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_announcement_user_reaction UNIQUE (announcement_id, user_id, reaction_type)
);

CREATE INDEX idx_reactions_announcement_id ON announcement_reactions (announcement_id);
